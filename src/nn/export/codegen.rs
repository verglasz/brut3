//! Generated Haskell code for the network: the decoded weights and the forward pass over the
//! fixed-width vector family, plus the stream decoder and a self-test.
//!
//! The vector types are not generated here. The Haskell side owns a `FixedVec` module made by
//! its `gen/vecgen.py` (strict records `VecN`, row containers `RowsM_N`, `dotN`, `selM_N`,
//! `linearM_N`/`denseM_N`/`residualM_M`, `sumK_N`/`reluSumK_N`, ...); the generated modules
//! import it and alias the role widths (`type VecA = Vec512`). [`vecgen_command`] lists the
//! shapes a configuration needs, as the command line that generates them.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::nn::model::MOVES;
use crate::nn::nnue::{
    BOARDS, CELLS, CONTENT_ROWS, CONTENTS, FEATURE_IDS, FEATURE_ROWS, IDS_PER_BOARD, NnueConfig,
    TOKENS,
};

/// The widths a configuration's code is generated with.
pub struct Names {
    pub e: usize,
    pub a: usize,
    pub h: usize,
    pub layers: usize,
}

impl Names {
    pub fn new(c: &NnueConfig) -> Self {
        Self {
            e: c.d_embed,
            a: c.d_acc,
            h: c.d_hidden,
            layers: c.layers,
        }
    }

    fn vec(w: usize) -> String {
        format!("Vec{w}")
    }

    fn rows(m: usize, n: usize) -> String {
        format!("Rows{m}_{n}")
    }

    /// `(m, n)` dense shapes: the fold, the hidden layers, the value head and the skip.
    fn dense(&self) -> Vec<(usize, usize)> {
        let mut shapes = vec![(self.a, self.e), (self.h, self.a)];
        if self.layers > 1 {
            shapes.push((self.h, self.h));
        }
        shapes.extend([(3, self.h), (3, self.a)]);
        shapes
    }

    /// Row containers read by index.
    fn selected(&self) -> Vec<(usize, usize)> {
        vec![(FEATURE_ROWS, self.a), (MOVES, self.h)]
    }
}

/// The `gen/vecgen.py` command line that generates every shape the configuration needs.
pub fn vecgen_command(names: &Names) -> String {
    let widths: BTreeSet<usize> = [3, CELLS, MOVES, names.e, names.a, names.h].into();
    let pairs = |shapes: &[(usize, usize)]| {
        shapes
            .iter()
            .map(|(m, n)| format!("{m}:{n}"))
            .collect::<Vec<_>>()
            .join(",")
    };
    let widths: Vec<String> = widths.iter().map(|w| w.to_string()).collect();
    format!(
        "python3 gen/vecgen.py --float {} --rows {} --dense {} --module FixedVec -o lib/FixedVec.hs",
        widths.join(" "),
        pairs(&names.selected()),
        pairs(&names.dense())
    )
}

fn header(out: &mut String, module: &str, exports: &str, opts: &str) {
    let _ = writeln!(out, "{{- FOURMOLU_DISABLE -}}");
    let _ = writeln!(out, "{{-# LANGUAGE Safe #-}}");
    if !opts.is_empty() {
        let _ = writeln!(out, "{{-# OPTIONS_GHC {opts} #-}}");
    }
    let _ = writeln!(
        out,
        "-- Generated by `ultimate-ttt-burn export`. Do not edit: regenerate instead."
    );
    let exports = if exports.is_empty() {
        String::new()
    } else {
        format!(" {exports}")
    };
    let _ = writeln!(out, "module {module}{exports} where\n");
}

fn vars(prefix: &str, n: usize) -> Vec<String> {
    (0..n).map(|i| format!("{prefix}{i}")).collect()
}

/// `Decode.hs`: base64 to signed 16-bit values, and rows off the stream.
pub fn decode_module(prefix: &str) -> String {
    let mut s = String::new();
    header(
        &mut s,
        &format!("{prefix}.Decode"),
        "(decodeStream, takeRows, only, single)",
        "-O2 -fobject-code",
    );
    s.push_str(
        r#"import Data.Bits (shiftL, shiftR, (.&.), (.|.))
import Data.Char (ord)

-- | Base64 text (standard alphabet, padded) as the signed 16-bit little-endian values it
-- encodes.
decodeStream :: String -> [Int]
decodeStream = pairs . bytes
  where
    pairs (lo : hi : rest) =
      let v = lo .|. (hi `shiftL` 8)
       in (if v >= 32768 then v - 65536 else v) : pairs rest
    pairs _ = []
    bytes (a : b : c : d : rest) =
      let n = (value a `shiftL` 18) .|. (value b `shiftL` 12) .|. (value c `shiftL` 6) .|. value d
          keep = if d == '=' then (if c == '=' then 1 else 2) else 3
       in take keep [(n `shiftR` 16) .&. 255, (n `shiftR` 8) .&. 255, n .&. 255] ++ bytes rest
    bytes [] = []
    bytes _ = error "decodeStream: ragged base64"
    value ch
      | ch >= 'A' && ch <= 'Z' = ord ch - ord 'A'
      | ch >= 'a' && ch <= 'z' = ord ch - ord 'a' + 26
      | ch >= '0' && ch <= '9' = ord ch - ord '0' + 52
      | ch == '+' = 62
      | ch == '/' = 63
      | otherwise = 0

-- | The next @rows@ rows of @cols@ values off the stream, each built by @mk@ from the scaled
-- values, and the rest of the stream.
takeRows :: Int -> Int -> Float -> ([Float] -> v) -> [Int] -> ([v], [Int])
takeRows rows cols scale mk = go rows
  where
    go 0 stream = ([], stream)
    go n stream =
      let (row, rest) = splitAt cols stream
          v = mk (map (\q -> fromIntegral q * scale) row)
          (vs, rest') = go (n - 1) rest
       in v `seq` (v : vs, rest')

-- | The one element of a one-element list (a bias row, a one-column value).
only :: [a] -> a
only [x] = x
only xs = error ("only: " ++ show (length xs) ++ " elements")

single :: [Float] -> Float
single = only
"#,
    );
    s
}

/// `Net.hs`: the decoded network and its forward pass.
pub fn net_module(names: &Names, prefix: &str, manifest_names: &[String]) -> String {
    let (e, a, h) = (names.e, names.a, names.h);
    let mut s = String::new();
    header(&mut s, &format!("{prefix}.Net"), "", "-O2 -fobject-code");
    let _ = writeln!(
        s,
        "-- Needs the FixedVec module generated by:\n--   {}\n",
        vecgen_command(names)
    );
    let _ = writeln!(s, "import FixedVec");
    let _ = writeln!(s, "import {prefix}.Decode");
    let _ = writeln!(s, "import {prefix}.Weights (chunks, manifest)\n");
    let _ = writeln!(s, "type VecE = {}", Names::vec(e));
    let _ = writeln!(s, "type VecA = {}", Names::vec(a));
    let _ = writeln!(s, "type VecH = {}\n", Names::vec(h));

    // The record.
    let _ = writeln!(s, "data Net = Net");
    let mut fields: Vec<(String, String, &str)> = vec![
        (
            "netContent".into(),
            "[VecE]".into(),
            "content rows by id (contents, no-forced, cells, pad)",
        ),
        (
            "netMix".into(),
            format!("[{}]", Names::rows(a, e)),
            "board k's first-layer slice, transposed",
        ),
        ("netMixBias".into(), "VecA".into(), ""),
        (
            "netForced".into(),
            Names::rows(a, e),
            "the forced board's slice",
        ),
        (
            "netFeatures".into(),
            Names::rows(FEATURE_ROWS, a),
            "feature rows by id",
        ),
    ];
    for i in 0..names.layers {
        let shape = if i == 0 {
            Names::rows(h, a)
        } else {
            Names::rows(h, h)
        };
        fields.push((format!("netHidden{i}"), shape, ""));
        fields.push((format!("netHidden{i}Bias"), "VecH".into(), ""));
    }
    fields.extend([
        ("netValue".into(), Names::rows(3, h), ""),
        ("netValueBias".into(), Names::vec(3), ""),
        ("netSkip".into(), Names::rows(3, a), ""),
        (
            "netPolicy".into(),
            Names::rows(MOVES, h),
            "global policy rows by move",
        ),
        ("netPolicyBias".into(), Names::vec(MOVES), ""),
        (
            "netLocal".into(),
            format!("[{}]", Names::vec(CELLS)),
            "each content's own cell logits",
        ),
        (
            "netSend".into(),
            "[Float]".into(),
            "each content's send logit",
        ),
    ]);
    for (i, (name, ty, comment)) in fields.iter().enumerate() {
        let sep = if i == 0 { "{" } else { "," };
        let comment = if comment.is_empty() {
            String::new()
        } else {
            format!("  -- {comment}")
        };
        let _ = writeln!(s, "  {sep} {name} :: !{ty}{comment}");
    }
    let _ = writeln!(s, "  }}\n");

    // Decoding: the stream in manifest order.
    let _ = writeln!(
        s,
        "-- | The network, decoded from the weight stream on first use."
    );
    let _ = writeln!(s, "net :: Net");
    let _ = writeln!(s, "net =");
    let _ = writeln!(s, "  let names = [n | (n, _, _, _) <- manifest]");
    let _ = writeln!(s, "      scales = [sc | (_, _, _, sc) <- manifest]");
    let _ = writeln!(s, "      expected = {}", hs_strings(manifest_names));
    let _ = writeln!(
        s,
        "      s0 = if names == expected then decodeStream (concat chunks) else error \"weight manifest does not match the generated decoder\""
    );
    let mut step = 0usize;
    let mut take = |s: &mut String, var: &str, rows: usize, cols: usize, mk: &str| {
        let _ = writeln!(
            s,
            "      ({var}, s{}) = takeRows {rows} {cols} (scales !! {step}) {mk} s{step}",
            step + 1
        );
        step += 1;
    };
    take(&mut s, "content", CONTENT_ROWS, e, &format!("fromList{e}"));
    for k in 0..BOARDS {
        take(&mut s, &format!("mix{k}"), a, e, &format!("fromList{e}"));
    }
    take(&mut s, "mixBias", 1, a, &format!("fromList{a}"));
    take(&mut s, "forced", a, e, &format!("fromList{e}"));
    take(&mut s, "features", FEATURE_ROWS, a, &format!("fromList{a}"));
    for i in 0..names.layers {
        let d_in = if i == 0 { a } else { h };
        take(
            &mut s,
            &format!("hidden{i}"),
            h,
            d_in,
            &format!("fromList{d_in}"),
        );
        take(
            &mut s,
            &format!("hidden{i}Bias"),
            1,
            h,
            &format!("fromList{h}"),
        );
    }
    take(&mut s, "value", 3, h, &format!("fromList{h}"));
    take(&mut s, "valueBias", 1, 3, "fromList3");
    take(&mut s, "skip", 3, a, &format!("fromList{a}"));
    take(&mut s, "policy", MOVES, h, &format!("fromList{h}"));
    take(&mut s, "policyBias", 1, MOVES, &format!("fromList{MOVES}"));
    take(
        &mut s,
        "local",
        CONTENTS,
        CELLS,
        &format!("fromList{CELLS}"),
    );
    take(&mut s, "send", CONTENTS, 1, "single");
    let _ = writeln!(s, "   in if null s{step} then Net");
    let mix_list: Vec<String> = (0..BOARDS)
        .map(|k| format!("fromListRows{a}_{e} mix{k}"))
        .collect();
    let mut inits = vec![
        "netContent = content".to_string(),
        format!("netMix = [{}]", mix_list.join(", ")),
        "netMixBias = only mixBias".to_string(),
        format!("netForced = fromListRows{a}_{e} forced"),
        format!("netFeatures = fromListRows{FEATURE_ROWS}_{a} features"),
    ];
    for i in 0..names.layers {
        let d_in = if i == 0 { a } else { h };
        inits.push(format!("netHidden{i} = fromListRows{h}_{d_in} hidden{i}"));
        inits.push(format!("netHidden{i}Bias = only hidden{i}Bias"));
    }
    inits.extend([
        format!("netValue = fromListRows3_{h} value"),
        "netValueBias = only valueBias".to_string(),
        format!("netSkip = fromListRows3_{a} skip"),
        format!("netPolicy = fromListRows{MOVES}_{h} policy"),
        "netPolicyBias = only policyBias".to_string(),
        "netLocal = local".to_string(),
        "netSend = send".to_string(),
    ]);
    for (i, init) in inits.iter().enumerate() {
        let sep = if i == 0 { "{" } else { "," };
        let _ = writeln!(s, "        {sep} {init}");
    }
    let _ = writeln!(s, "        }}");
    let _ = writeln!(
        s,
        "      else error \"weight stream longer than the manifest\"\n"
    );

    // Forward pieces.
    let _ = writeln!(s, "zeroA :: VecA");
    let _ = writeln!(s, "zeroA = replicate{a} 0\n");
    let _ = writeln!(s, "zero3 :: Vec3");
    let _ = writeln!(s, "zero3 = replicate3 0\n");
    let _ = writeln!(
        s,
        "-- | The folded first-layer row of a board token at board k (k = {BOARDS} for the forced\n\
         -- token): what a table of rows per content caches."
    );
    let _ = writeln!(s, "foldRow :: Net -> Int -> VecE -> VecA");
    let _ = writeln!(
        s,
        "foldRow n k t = linear{a}_{e} (if k == {BOARDS} then netForced n else netMix n !! k) zeroA t\n"
    );
    let _ = writeln!(
        s,
        "-- | The accumulator from the ten folded rows and the eleven feature ids."
    );
    let _ = writeln!(s, "accumulateRows :: Net -> [VecA] -> [Int] -> VecA");
    let rs = vars("r", TOKENS);
    let fs = vars("f", FEATURE_IDS);
    let feats: Vec<String> = fs
        .iter()
        .map(|f| format!("(sel{FEATURE_ROWS}_{a} {f} (netFeatures n))"))
        .collect();
    let mut terms = vec!["(netMixBias n)".to_string()];
    terms.extend(rs.iter().cloned());
    terms.extend(feats);
    let _ = writeln!(
        s,
        "accumulateRows n [{}] [{}] = relu{a} ({})",
        rs.join(", "),
        fs.join(", "),
        nested_sum(&format!("add{a}"), &terms)
    );
    let _ = writeln!(
        s,
        "accumulateRows _ _ _ = error \"accumulateRows: {TOKENS} rows and {FEATURE_IDS} feature ids\"\n"
    );
    let _ = writeln!(s, "-- | The last hidden layer.");
    let _ = writeln!(s, "hiddenOf :: Net -> VecA -> VecH");
    let mut expr = format!("dense{h}_{a} (netHidden0 n) (netHidden0Bias n) acc");
    for i in 1..names.layers {
        expr = format!("residual{h}_{h} (netHidden{i} n) (netHidden{i}Bias n) ({expr})");
    }
    let _ = writeln!(s, "hiddenOf n acc = {expr}\n");
    let _ = writeln!(s, "-- | Win, draw and loss logits.");
    let _ = writeln!(s, "wdlOf :: Net -> VecA -> VecH -> Vec3");
    let _ = writeln!(
        s,
        "wdlOf n acc h = add3 (linear3_{h} (netValue n) (netValueBias n) h) (linear3_{a} (netSkip n) zero3 acc)\n"
    );
    let _ = writeln!(
        s,
        "-- | The global part of a move's logit (move index = board * 9 + square); the full logit\n\
         -- adds index{CELLS} square (netLocal n !! board content) + netSend n !! square content."
    );
    let _ = writeln!(s, "policyLogit :: Net -> VecH -> Int -> Float");
    let _ = writeln!(
        s,
        "policyLogit n h m = dot{h} (sel{MOVES}_{h} m (netPolicy n)) h + index{MOVES} m (netPolicyBias n)\n"
    );
    let _ = writeln!(
        s,
        "-- | A board token from its {IDS_PER_BOARD} ids, looking the rows up in the content list\n\
         -- (slow: for tests and for building a table, not for the search)."
    );
    let _ = writeln!(s, "tokenOf :: Net -> [Int] -> VecE");
    let ids = vars("i", IDS_PER_BOARD);
    let rows: Vec<String> = ids
        .iter()
        .map(|i| format!("(netContent n !! {i})"))
        .collect();
    let _ = writeln!(
        s,
        "tokenOf n [{}] = {}",
        ids.join(", "),
        nested_sum(&format!("add{e}"), &rows)
    );
    let _ = writeln!(s, "tokenOf _ _ = error \"tokenOf: {IDS_PER_BOARD} ids\"\n");
    s
}

/// `add a (add b (add c d))`: a sum of vectors as nested binary adds, which the INLINE
/// `combineN` of FixedVec lets GHC collapse into one constructor application.
fn nested_sum(add: &str, terms: &[String]) -> String {
    match terms {
        [] => "0".to_string(),
        [one] => one.clone(),
        [first, rest @ ..] => format!("({add} {first} {})", nested_sum(add, rest)),
    }
}

fn hs_strings(items: &[String]) -> String {
    let quoted: Vec<String> = items.iter().map(|s| format!("{s:?}")).collect();
    format!("[{}]", quoted.join(", "))
}

/// `SelfTest.hs`: evaluates the reference positions from their ids and compares.
pub fn selftest_module(names: &Names, prefix: &str) -> String {
    let (a, h) = (names.a, names.h);
    let mut s = String::new();
    header(
        &mut s,
        &format!("{prefix}.SelfTest"),
        "(selfTest, evalIds, bench)",
        "-O2 -fobject-code",
    );
    let _ = writeln!(s, "import GHC.Clock (getMonotonicTimeNSec)");
    let _ = writeln!(s, "import FixedVec");
    let _ = writeln!(s, "import {prefix}.Net");
    let _ = writeln!(s, "import {prefix}.Reference");
    let _ = writeln!(s, "import {prefix}.Spec\n");
    let text = format!(
        r#"-- | Accumulator, last hidden layer and the three logits from a position's ids.
evalIds :: Net -> [Int] -> (VecA, VecH, Vec3)
evalIds n ids =
  let tokenIds = take (tokens * idsPerBoard) ids
      featureIds' = drop (tokens * idsPerBoard) ids
      toks = [tokenOf n (take idsPerBoard (drop (k * idsPerBoard) tokenIds)) | k <- [0 .. tokens - 1]]
      rows = zipWith (foldRow n) [0 ..] toks
      acc = accumulateRows n rows featureIds'
      hid = hiddenOf n acc
   in (acc, hid, wdlOf n acc hid)

-- | A move's full logit: the global head plus the board's own cell logit and the send logit.
moveLogit :: Net -> [Int] -> VecH -> Int -> Float
moveLogit n ids hid m =
  let board = m `div` 9
      square = m `mod` 9
      content b = ids !! (b * idsPerBoard)
   in policyLogit n hid m + index9 square (netLocal n !! content board) + netSend n !! content square

softmax :: [Float] -> [Float]
softmax zs = let m = maximum zs; es = map (\z -> exp (z - m)) zs; t = sum es in map (/ t) es

maxAbsDiff :: [Float] -> [Float] -> Float
maxAbsDiff xs ys = maximum (0 : zipWith (\x y -> abs (x - y)) xs ys)

-- | Compares every reference position; prints the largest deviations and whether they are
-- within tolerance (1e-2 on pre-activation sums, 1e-3 on probabilities).
selfTest :: IO Bool
selfTest = do
  let n = net
      results =
        [ [maxAbsDiff (toList{a} acc) (refAcc r), maxAbsDiff (toList{h} hid) (refHidden r), maxAbsDiff (toList3 wdl) (refWdlLogits r), maxAbsDiff (softmax (toList3 wdl)) (refWdl r), maxAbsDiff logits refLogits, maxAbsDiff (softmax logits) refProbs]
        | r <- refs
        , let (acc, hid, wdl) = evalIds n (refIds r)
        , let moves = [m | (m, _, _) <- refPolicy r]
        , let refLogits = [l | (_, l, _) <- refPolicy r]
        , let refProbs = [p | (_, _, p) <- refPolicy r]
        , let logits = map (moveLogit n (refIds r) hid) moves
        ]
      worst = foldr1 (zipWith max) results
      labels = ["acc", "hidden", "wdl logits", "wdl", "policy logits", "policy"]
      limits = [1e-2, 1e-2, 1e-2, 1e-3, 1e-2, 1e-3]
      ok = and (zipWith (<) worst limits)
  putStrLn ("self-test over " ++ show (length refs) ++ " positions, largest deviations: " ++ unwords [l ++ " " ++ show w | (l, w) <- zip labels worst])
  putStrLn (if ok then "self-test passed" else "self-test FAILED")
  return ok

-- | Times the per-evaluation work after the fold (accumulator, hidden layers, value head and
-- nine policy logits) over the reference positions, printing microseconds per evaluation.
bench :: Int -> IO ()
bench iters = do
  let n = net
      inputs =
        [ (rows, featureIds')
        | r <- refs
        , let ids = refIds r
        , let tokenIds = take (tokens * idsPerBoard) ids
        , let featureIds' = drop (tokens * idsPerBoard) ids
        , let toks = [tokenOf n (take idsPerBoard (drop (k * idsPerBoard) tokenIds)) | k <- [0 .. tokens - 1]]
        , let rows = zipWith (foldRow n) [0 ..] toks
        ]
      count = length inputs
      step :: Int -> Float -> Float
      step i total =
        let (rows, fids) = inputs !! (i `mod` count)
            acc = accumulateRows n rows fids
            hid = hiddenOf n acc
            wdl = wdlOf n acc hid
            pol = sum [policyLogit n hid (9 * (i `mod` 9) + sq) | sq <- [0 .. 8]]
         in total + index3 0 wdl + pol
      loop :: Int -> Float -> Float
      loop i total | i >= iters = total
                   | otherwise = let total' = step i total in total' `seq` loop (i + 1) total'
  warm <- return $! sum (map (\(rows, _) -> sum (map (index{a} 0) rows)) inputs)
  t0 <- getMonotonicTimeNSec
  total <- return $! loop 0 warm
  t1 <- getMonotonicTimeNSec
  putStrLn ("bench: " ++ show (fromIntegral (t1 - t0) / 1000 / fromIntegral iters :: Double) ++ " us per evaluation (checksum " ++ show total ++ ")")
"#
    );
    s.push_str(&text);
    s
}
